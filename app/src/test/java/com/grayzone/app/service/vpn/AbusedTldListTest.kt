package com.grayzone.app.service.vpn

import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Assume.assumeTrue
import org.junit.Test
import java.io.ByteArrayInputStream
import java.io.File

/**
 * Bare-TLD blocks are the one place we intentionally match a single label, so the
 * boundary between "under a blocked TLD" and "merely named after one" is pinned here.
 */
class AbusedTldListTest {

    private val list = AbusedTldList.parse(sequenceOf("zip", "mov", "surf", "country"))

    @Test
    fun `hostname under a blocked tld is blocked at any depth`() {
        assertTrue(list.blocks("example.zip"))
        assertTrue(list.blocks("downloads.example.zip"))
        assertTrue(list.blocks("a.b.c.mov"))
    }

    @Test
    fun `blocked tld used as a non-final label stays reachable`() {
        assertFalse(list.blocks("zip.example.com"))
        assertFalse(list.blocks("mov.surf.example.com"))
        assertFalse(list.blocks("example.zipper"))
        assertFalse(list.blocks("example.unzip"))
    }

    @Test
    fun `unlisted tlds are never blocked`() {
        assertFalse(list.blocks("example.com"))
        assertFalse(list.blocks("developer.android.com"))
    }

    @Test
    fun `dotless and malformed inputs never match`() {
        assertFalse(list.blocks("zip"))
        assertFalse(list.blocks(""))
        assertFalse(list.blocks("."))
        assertFalse(list.blocks(".zip"))
        assertFalse(list.blocks("example.zip."))
    }

    @Test
    fun `parser keeps only bare tlds`() {
        val parsed = AbusedTldList.parse(
            sequenceOf(
                "# comment",
                "",
                "   ",
                "ZIP",
                "co.com",       // multi-label suffix: handled by the ads bloom filter
                "dpdns.org",
                "xn--p1ai",
                "-bad",
                "bad-",
                "sp ace",
                "zip"           // duplicate
            )
        )
        assertEquals(2, parsed.size)
        assertTrue(parsed.blocks("host.zip"))
        assertTrue(parsed.blocks("host.xn--p1ai"))
        assertFalse(parsed.blocks("host.co.com"))
    }

    @Test
    fun `empty list blocks nothing`() {
        assertFalse(AbusedTldList.EMPTY.blocks("example.zip"))
        assertEquals(0, AbusedTldList.EMPTY.size)
    }

    @Test
    fun `readFrom parses a utf8 stream with a bom and comment header`() {
        val text = "\uFEFF# Generated by scripts/blocklist_tools.ps1\nzip\nmov\n"
        val parsed = AbusedTldList.readFrom(ByteArrayInputStream(text.toByteArray(Charsets.UTF_8)))
        assertEquals(2, parsed.size)
        assertTrue(parsed.blocks("example.mov"))
    }

    @Test
    fun `shipped resource covers the tlds this feature exists for`() {
        val resource = File("src/main/res/raw/abused_tlds.txt")
        assumeTrue("run scripts/blocklist_tools.ps1 to generate the list", resource.exists())

        val shipped = resource.inputStream().use { AbusedTldList.readFrom(it) }
        assertTrue("expected a full TLD feed, got ${shipped.size}", shipped.size > 200)
        for (host in listOf("payload.zip", "clip.mov", "phish.surf", "spam.cyou")) {
            assertTrue("$host must be blocked", shipped.blocks(host))
        }
        for (host in listOf("example.com", "wikipedia.org", "developer.android.com", "pages.github.io")) {
            assertFalse("$host must stay reachable", shipped.blocks(host))
        }
    }
}
