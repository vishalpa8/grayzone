package com.grayzone.app.service.vpn

import java.io.InputStream

/**
 * Exact-match set of "most abused" top-level domains (e.g. "zip", "mov", "surf").
 *
 * HaGeZi's spam-TLD feed is mostly bare, dotless entries. Those cannot live in the
 * Bloom filters: [DomainZoneMatcher] deliberately never queries a bare TLD, because a
 * Bloom false positive on "com" would blackhole the entire internet. This list is
 * therefore shipped as a plain text resource and matched exactly, so there is no
 * false-positive risk in exchange for blocking a whole TLD.
 *
 * Only the final label is compared, so "zip.example.com" stays reachable while
 * "downloads.example.zip" is blocked.
 *
 * Generated by scripts/blocklist_tools.ps1 into res/raw/abused_tlds.txt.
 */
class AbusedTldList private constructor(private val tlds: Set<String>) {

    val size: Int get() = tlds.size

    /** True if [domain] (already normalized: lowercase, no trailing dot) sits under a blocked TLD. */
    fun blocks(domain: String): Boolean {
        val lastDot = domain.lastIndexOf('.')
        // A dotless query is not a public hostname; never let it match a TLD entry.
        if (lastDot <= 0 || lastDot == domain.length - 1) return false
        return tlds.contains(domain.substring(lastDot + 1))
    }

    companion object {
        val EMPTY = AbusedTldList(emptySet())

        fun readFrom(stream: InputStream): AbusedTldList =
            stream.bufferedReader(Charsets.UTF_8).use { reader ->
                parse(reader.lineSequence())
            }

        /**
         * Keeps single-label entries only. Multi-label rows in the same upstream feed
         * (e.g. "co.com", "us.kg") are suffix blocks already covered by the ads Bloom
         * filter's parent-zone walk, so they are skipped here rather than duplicated.
         */
        fun parse(lines: Sequence<String>): AbusedTldList {
            val tlds = HashSet<String>()
            for (raw in lines) {
                val line = raw.trim().trim('\uFEFF').lowercase()
                if (line.isEmpty() || line.startsWith("#")) continue
                if (line.contains('.')) continue
                if (!isValidLabel(line)) continue
                tlds.add(line)
            }
            return AbusedTldList(tlds)
        }

        private fun isValidLabel(label: String): Boolean {
            if (label.length > 63) return false
            if (label.startsWith("-") || label.endsWith("-")) return false
            return label.all { it in 'a'..'z' || it in '0'..'9' || it == '-' }
        }
    }
}
